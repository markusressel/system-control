package wifi

import (
	"github.com/markusressel/system-control/internal/configuration"
	"github.com/markusressel/system-control/internal/wifi"
	"github.com/spf13/cobra"
)

var onCmd = &cobra.Command{
	Use:   "on",
	Short: "Turn on the WiFi Hotspot",
	Long:  ``,
	Args:  cobra.NoArgs,
	RunE: func(cmd *cobra.Command, args []string) error {
		iface, ssid, err := hotspotSettings()
		if err != nil {
			return err
		}

		return wifi.TurnOnHotspot(
			createHotspotConfigName(ssid),
			iface,
			ssid,
			firstNonEmpty(password, configuration.Get().Hotspot.Password),
		)
	},
}

func init() {
	Command.AddCommand(onCmd)

	onCmd.Flags().StringVarP(
		&password,
		"password", "p",
		"",
		"Password of the hotspot (default: from configuration, else generated by NetworkManager)",
	)
}
